def _question_map(doubt_summaries):
    """{doubt id: question id} for every member of every question, from the
    summaries whose register is valid."""
    out = {}
    for s in doubt_summaries or []:
        if s.get("register_errors"):
            continue
        for q in s.get("questions") or []:
            for m in q.get("members") or []:
                out.setdefault(m["doubt"], q["id"])
    return out


def _doubt_sheet_rows(tcs, doubt_summaries):
    """Rows of the Doubts sheet for the selected test cases: one dict per
    question that touches a selected test case (impact order restricted to the
    selection), then one per ungrouped doubt of a selected test case."""
    by_sid = {fm.get("scenario_id"): fm for _r, fm, _b in tcs if fm.get("scenario_id")}
    tc_order = {sid: i for i, sid in enumerate(by_sid)}
    labels = dict(CONF_PARTS)
    part_order = {k: i for i, (k, _l) in enumerate(CONF_PARTS)}

    def affected(members):
        ms = sorted(members, key=lambda m: (tc_order[m["scenario_id"]],
                                            part_order.get(m["part"], 99), m["doubt"]))
        return [f"{_display_id(by_sid[m['scenario_id']])} / "
                f"{labels.get(m['part'], m['part'])}" for m in ms]

    questions, ungrouped = [], []
    for s in doubt_summaries or []:
        if s.get("register_errors"):
            pool = [d for d in s.get("doubts") or [] if d.get("state") != "closed"]
            ungrouped += [d for d in pool if d["scenario_id"] in by_sid]
            continue
        ungrouped += [d for d in s.get("ungrouped_doubts") or []
                      if d["scenario_id"] in by_sid]
        for q in s.get("questions") or []:
            mine = [m for m in q.get("members") or [] if m["scenario_id"] in by_sid]
            if not mine:
                continue
            live = [m for m in mine if m["state"] != "closed"]
            low = sum(1 for m in live if m["level"] == "Low")
            rids = sorted({m["resolution"] for m in mine if m.get("resolution")})
            questions.append({
                "id": q["id"], "question": q.get("question") or "",
                "status": q.get("status") or "",
                "tcs": len({m["scenario_id"] for m in mine}),
                "lowest": "Low" if low else "Medium" if live else "",
                "affected": affected(mine), "answer": ", ".join(rids),
                "_key": (-len({m["scenario_id"] for m in live}), -low, str(q["id"])),
            })
    questions.sort(key=lambda r: r["_key"])
    for r in questions:
        del r["_key"]
    rows = list(questions)
    for d in sorted(ungrouped, key=lambda d: d["doubt"]):
        rows.append({"id": "-", "question": d.get("remark") or "",
                     "status": "ungrouped", "tcs": 1,
                     "lowest": d["level"], "affected": affected([d]), "answer": ""})
    return rows


