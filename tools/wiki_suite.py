    ws.cell(row=r, column=1, value=section).font = st["blue"]
    r += 1
    pre_lists = [_precond_lines(b) for _r, _f, b in all_tcs]
    common = [ln for ln in (pre_lists[0] if pre_lists else [])
              if all(ln in pl for pl in pre_lists[1:])]
    if common:
        ws.cell(row=r, column=1, value="<Pre-condition>").font = st["blue"]
        r += 1
        for i, ln in enumerate(common, 1):
            # blue block is whole-cell bold already — markers stripped, dashes fixed
            ws.cell(row=r, column=1, value=f"{i}. {_plain(ln)}").font = st["blue"]
            r += 1
