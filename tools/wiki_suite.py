def tc_sort_key(fm):
    # A TC covering a flow journey fragment (#J\d+) sorts by journey position
    # ahead of everything, so UAT sheets read in walk order (module key "" wins).
    for ref in fm.get("covers") or []:
        rel, frag = resolve_ref(ref)
        if rel.startswith("flows/") and frag and re.match(r"^J\d+$", frag):
            # The journey's walk order when the renderer recorded it (`order`),
            # so an entry inserted mid-journey sits where it runs; the journey
            # number for test cases rendered before `order` existed.
            pos = fm["order"] if isinstance(fm.get("order"), int) else int(frag[1:])
            return ("", (), 0, pos, fm["id"])
    m = re.match(r"^(?:UAT-)?(\d[\d.]*)-AC(\d+)-(\d+)$", fm["id"])
    if not m:
        return (fm.get("module") or "", (), 999, 999, fm["id"])
    prefix = tuple(int(p) for p in m.group(1).split("."))
    if isinstance(fm.get("order"), int):
        # Flow order (tc-style R6): the spec's run order, so a section's test
        # cases read top-down as one chain rather than AC-number order.
        return (fm.get("module") or "", prefix, 0, fm["order"], fm["id"])
    return (fm.get("module") or "", prefix, int(m.group(2)), int(m.group(3)),
            fm["id"])


def tc_prds(fm):
    """The PRD ids a test case draws on: the keys of its
    generated_from.prd_versions. An old-form test case (prd_version only)
    draws on none."""
    return set((fm.get("generated_from") or {}).get("prd_versions") or {})


def check_prd_filters(suite, manifest):
    """include_prds / exclude_prds must name registered PRDs. A typo would
    otherwise select nothing (or exclude nothing) without a word."""
    reg = prd_registry(manifest)
    for key in ("include_prds", "exclude_prds"):
        vals = suite.get(key) or []
        if not isinstance(vals, list):
            raise ValueError(f"{key} must be a list of PRD ids, got {vals!r}")
        # A mapping or a list as an element is unhashable: `v not in reg`
        # would raise instead of refusing.
        bad = [v for v in vals if not isinstance(v, str) or v not in reg]
        if bad:
            raise ValueError(
                f"{key} names unknown PRD id(s) {bad}; registered: "
                f"{', '.join(sorted(reg)) or '(none)'}")


def prd_names(tcs, manifest):
    """'<title> - v<adopted>' for every PRD the given test cases draw on,
    sorted by PRD id. Never 'vNone' (wiki.prd_version_text's policy): a PRD
    with nothing adopted says so, and an id the registry does not hold is
    named as unregistered."""
    reg = prd_registry(manifest)
    ids = sorted({pid for _r, fm, _b in tcs for pid in tc_prds(fm)})

    def name(pid):
        if pid not in reg:
            return f"{pid} (unregistered)"
        v = adopted_version(manifest, pid)
        return (f"{reg[pid].get('title') or pid} - "
                + (f"v{v}" if v is not None else "no adopted version"))
    return [name(pid) for pid in ids]


def prd_docs(tcs, manifest, project_name):
    """Rows of the Proj Doc References sheet: one per PRD the selected test
    cases draw on; with none, a single row naming the project, no version."""
    return ([("PRD", n) for n in prd_names(tcs, manifest)]
            or [("PRD", project_name)])


def select(suite, concepts):
    """Returns (selected, retired, stale_included) lists of (rel, fm, body)."""
    kind = suite.get("kind", "sit")
    inc_mod = suite.get("include_modules") or []
    exc_mod = suite.get("exclude_modules") or []
    inc_flow = suite.get("include_flows") or []
    exc_flow = suite.get("exclude_flows") or []
    inc_prd = set(suite.get("include_prds") or [])
    exc_prd = set(suite.get("exclude_prds") or [])
    prios = suite.get("priorities") or []
    extra_inc = set(suite.get("extra_include") or [])
    extra_exc = set(suite.get("extra_exclude") or [])

    selected, retired, stale = [], [], []
    for rel, (fm, body, _p) in sorted(concepts.items()):
        if not fm or fm.get("type") != "Test Case":
            continue
        if kind != "mixed" and fm.get("kind") != kind:
            continue
        mod = Path(resolve_ref(fm["module"])[0]).name if fm.get("module") else None
        flow = Path(resolve_ref(fm["flow"])[0]).name if fm.get("flow") else None
        in_scope = True
        if inc_mod and (mod not in inc_mod):
            in_scope = False
        if mod in exc_mod:
            in_scope = False
        if inc_flow and (flow not in inc_flow):
            in_scope = False
        if flow in exc_flow:
            in_scope = False
        prds = tc_prds(fm)
        if inc_prd and not (prds & inc_prd):
            in_scope = False
        if prds & exc_prd:
            in_scope = False
        if prios and fm.get("priority") not in prios:
            in_scope = False
        if fm["id"] in extra_inc:
            in_scope = True
        if fm["id"] in extra_exc:          # subtractive wins (spec §9)
            in_scope = False
        if not in_scope:
            continue
        st = fm.get("status")
        if st == "active":
            selected.append((rel, fm, body))
        elif st == "retired":
            retired.append((rel, fm, body))
        elif st == "stale":
            stale.append((rel, fm, body))
    keyf = lambda t: tc_sort_key(t[1])
    return sorted(selected, key=keyf), sorted(retired, key=keyf), sorted(stale, key=keyf)


