            extra = [ln for ln in _precond_lines(body) if ln not in common]
            if extra:
                # tc-style R5: TC-specific setup appends as bare lines — no
                # "Pre-condition:" label, no numbering (shared lines live in
                # the sheet's blue <Pre-condition> block).
                lines = "\n".join(extra)
                data = f"{data}\n\n{lines}".strip() if data else lines
            vals = (_display_id(fm), _scenario_cell(fm, body, concepts),
                    body_section(body, "Steps") or "", data,
                    body_section(body, "Expected Results") or "")
