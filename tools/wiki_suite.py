def write_sidecar(xlsx_path, source, tc_rels, manifest):
    """Record what a compiled workbook was built from, beside it: the compile
    time, the wiki commit, the source (suite or export) and the sealed hash of
    every test case in it. The operator app compares these hashes with the
    manifest to say which rows changed since the compile. Returns the path
    written (`xlsx_path` with a .json suffix). build/ is a compiled view: this
    is called only by `suite compile` and `export`, and the file is never
    edited. `tc_rels` must be in the order the workbook holds the rows (what
    `render_xlsx` returns); `tcs_order: "sheet"` records that promise."""
    import json
    import subprocess
    hashes = manifest.get("tc_hashes") or {}
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                          capture_output=True, text=True)
    doc = {"compiled_at": now_iso(),
           "wiki_commit": head.stdout.strip() if head.returncode == 0 else None,
           "source": source,
           "tcs_order": "sheet",
           "tcs": {rel: hashes.get(rel) for rel in tc_rels}}
    path = Path(xlsx_path).with_suffix(".json")
    path.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n",
                    encoding="utf-8", newline="\n")
    return path


