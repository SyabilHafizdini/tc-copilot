def _fm_of(concepts, rel):
    c = concepts.get(rel)
    return c[0] if c else None


# tc-style contract (skill .claude/skills/tc-style): workbook text uses
# hyphens (never em/en dashes) and renders `**...**` markers as real bold.
_DASHES = {0x2014: "-", 0x2013: "-"}
_BOLD_RE = re.compile(r"\*\*(.+?)\*\*", re.DOTALL)


def _plain(text):
    """Marker-free, dash-normalized text (for height estimation / md output)."""
    return _BOLD_RE.sub(r"\1", str(text).translate(_DASHES))


def _richify(text):
    """Cell value per tc-style: em/en dashes -> hyphens; '**...**' markers ->
    rich-text bold runs. Returns a plain str when nothing is bold."""
    s = str(text).translate(_DASHES)
    if "**" not in s:
        return s
    from openpyxl.cell.rich_text import CellRichText, TextBlock
    from openpyxl.cell.text import InlineFont
    bold = InlineFont(rFont="Arial", sz=10, b=True)
    rich = CellRichText()
    for i, part in enumerate(_BOLD_RE.split(s)):
        if part:
            rich.append(TextBlock(bold, part) if i % 2 else part)
    return rich


def _display_id(fm):
    # Org sheets prefix ids with "TC-" (e.g. TC-1.1.3.1.1-AC1-01); the sheet's
    # Total-TC COUNTIF and the Test Statistics VLOOKUPs key off this form.
    # UAT ids carry a "UAT-" prefix in the wiki; strip it to the org "TC-" form.
    tid = fm["id"]
    if tid.startswith("UAT-"):
        return "TC-" + tid[4:]
    return tid if tid.startswith(("TC-", "BR-")) else f"TC-{tid}"


def _ac_text(fm, concepts):
    for ref in fm.get("covers") or []:
        rel, frag = resolve_ref(ref)
        sfm = _fm_of(concepts, rel)
        if not (sfm and frag):
            continue
        for key in ("acceptance_criteria", "branches"):
            for ac in sfm.get(key) or []:
                if ac.get("id") == frag:
                    return ac.get("text") or ""
    return ""


def _scenario_cell(fm, body, concepts):
    """Template Scenario column: 'Scenario/Given/When/Then' parsed from the
    covered AC's Gherkin-in-prose text; falls back to the TC objective."""
    text = " ".join(_ac_text(fm, concepts).split())
    m = re.match(r"^(?P<t>.+?\.)\s+Given (?P<g>.+?), when (?P<w>.+?), then (?P<n>.+)$",
                 text, re.IGNORECASE)
    if m:
        g, w, n = (m.group(k).rstrip(".") for k in "gwn")
        return (f"**Scenario:** {m.group('t')}\n\n**Given:** {g[:1].upper()}{g[1:]}.\n\n"
                f"**When:** {w[:1].upper()}{w[1:]}.\n\n**Then:** {n[:1].upper()}{n[1:]}.")
    obj = body_section(body, "Objective") or fm.get("description") or ""
    return f"**Scenario:** {fm['title']}.\n\n{obj}".strip()


def _precond_lines(body):
    sec = body_section(body, "Preconditions") or ""
    return [re.sub(r"^\d+\.\s*", "", ln.strip())
            for ln in sec.splitlines() if ln.strip()]


def _subgroup_of(fm, concepts):
    """(rel, fm) of the first covering story; falls back to the flow.

    Story-from-covers is tried FIRST so UAT sheets (whose TCs carry a `flow`
    but cover a story AC) group by screen (the member story) rather than
    collapsing every UAT TC under the single flow."""
    for ref in fm.get("covers") or []:
        rel, _frag = resolve_ref(ref)
        sfm = _fm_of(concepts, rel)
        if sfm and sfm.get("type") == "User Story":
            return rel, sfm
    if fm.get("flow"):
        rel = resolve_ref(fm["flow"])[0]
        return rel, _fm_of(concepts, rel)
    return None, None


def _group(tcs, concepts):
    """[(mod_rel, mod_fm, [(sub_rel, sub_fm, [tc, ...]), ...]), ...]
    Modules and subgroups keep first-TC order (tcs arrive sorted)."""
    mods, order = {}, []
    for rel, fm, body in tcs:
        mrel = resolve_ref(fm.get("module") or fm.get("flow") or "unassigned")[0]
        if mrel not in mods:
            mods[mrel] = {}
            order.append(mrel)
        srel, sfm = _subgroup_of(fm, concepts)
        mods[mrel].setdefault(srel, (sfm, []))[1].append((rel, fm, body))
    return [(mrel, _fm_of(concepts, mrel),
             [(srel, sfm, tcl) for srel, (sfm, tcl) in mods[mrel].items()])
            for mrel in order]


def _sheet_name(mod_fm, idx):
    desc = (mod_fm or {}).get("description") or ""
    m = re.search(r"§(\d+(?:\.\d+)*)", desc)
    sec = m.group(1) if m else str(idx + 1)
    title = _plain((mod_fm or {}).get("title") or "Test Cases")
    name = f"C-TC-{sec} ({title})"
    while len(name) > 31:                    # Excel sheet-name hard limit
        words = title.split()
        i = max(range(len(words)), key=lambda j: len(words[j]))
        if len(words[i]) <= 4:
            title = title[:len(title) - (len(name) - 31)].rstrip()
            name = f"C-TC-{sec} ({title})"
            break
        words[i] = words[i][:4]
        title = " ".join(words)
        name = f"C-TC-{sec} ({title})"
    return re.sub(r"[\[\]:*?/\\']", "-", name)


def _est_height(vals):
    lines = 1
    for col, val in zip("ABCDE", vals):
        if not val:
            continue
        w = max(COL_W[col] - 2, 10)
        n = sum(max(1, math.ceil(len(ln) / w)) for ln in _plain(val).split("\n"))
        lines = max(lines, n)
    return min(max(14 * lines, 20), 400)


