def _confidence_remarks(fm, qmap=None):
    """The Remarks cell: one `**Column**: Level - remark` line per reviewed
    column (tc-style R7). Falls back to a single remark for a test case
    rendered before confidence was rated per part. `qmap` maps a doubt id
    (`<scenario_id>#<part>`) to its question id, shown as `Level [Q-...]`."""
    qmap = qmap or {}
    parts = fm.get("confidence_parts")
    if isinstance(parts, dict) and parts:
        lines = []
        for key, label in CONF_PARTS:
            p = parts.get(key) or {}
            if p.get("level"):
                remark = str(p.get("remark") or "").strip() or "stated by the source."
                qid = qmap.get(f"{fm.get('scenario_id')}#{key}")
                tag = f" [{qid}]" if qid else ""
                lines.append(f"**{label}**: {p['level']}{tag} - {remark}")
        return "\n".join(lines)
    return str(fm.get("confidence_remarks") or "")


def _fm_of(concepts, rel):
    c = concepts.get(rel)
    return c[0] if c else None


# tc-style contract (skill .claude/skills/tc-style): workbook text uses
# hyphens (never em/en dashes) and renders `**...**` markers as real bold.
_DASHES = {0x2014: "-", 0x2013: "-"}
_BOLD_RE = re.compile(r"\*\*(.+?)\*\*", re.DOTALL)


def _plain(text):
    """Marker-free, dash-normalized text (for height estimation / md output)."""
    return _BOLD_RE.sub(r"\1", str(text).translate(_DASHES))


def _richify(text):
    """Cell value per tc-style: em/en dashes -> hyphens; '**...**' markers ->
    rich-text bold runs. Returns a plain str when nothing is bold."""
    s = str(text).translate(_DASHES)
    if "**" not in s:
        return s
    from openpyxl.cell.rich_text import CellRichText, TextBlock
    from openpyxl.cell.text import InlineFont
    bold = InlineFont(rFont="Arial", sz=10, b=True)
    rich = CellRichText()
    for i, part in enumerate(_BOLD_RE.split(s)):
        if part:
            rich.append(TextBlock(bold, part) if i % 2 else part)
    return rich


def _display_id(fm):
    # Org sheets prefix ids with "TC-" (e.g. TC-1.1.3.1.1-AC1-01); the sheet's
    # Total-TC COUNTIF and the Test Statistics VLOOKUPs key off this form.
    # UAT ids carry a "UAT-" prefix in the wiki; strip it to the org "TC-" form.
    tid = fm["id"]
    if tid.startswith("UAT-"):
        return "TC-" + tid[4:]
    return tid if tid.startswith(("TC-", "BR-")) else f"TC-{tid}"


def _ac_text(fm, concepts):
    for ref in fm.get("covers") or []:
        rel, frag = resolve_ref(ref)
        sfm = _fm_of(concepts, rel)
        if not (sfm and frag):
            continue
        for key in ("acceptance_criteria", "branches"):
            for ac in sfm.get(key) or []:
                if ac.get("id") == frag:
                    return ac.get("text") or ""
    return ""


def _scenario_cell(fm, body, concepts):
    """Template Scenario column: 'Scenario/Given/When/Then' parsed from the
    covered AC's Gherkin-in-prose text; falls back to the TC objective."""
    text = " ".join(_ac_text(fm, concepts).split())
    m = re.match(r"^(?P<t>.+?\.)\s+Given (?P<g>.+?), when (?P<w>.+?), then (?P<n>.+)$",
                 text, re.IGNORECASE)
    if m:
        g, w, n = (m.group(k).rstrip(".") for k in "gwn")
        return (f"**Scenario:** {m.group('t')}\n\n**Given:** {g[:1].upper()}{g[1:]}.\n\n"
                f"**When:** {w[:1].upper()}{w[1:]}.\n\n**Then:** {n[:1].upper()}{n[1:]}.")
    obj = body_section(body, "Objective") or fm.get("description") or ""
    return f"**Scenario:** {fm['title']}.\n\n{obj}".strip()


def _precond_lines(body):
    sec = body_section(body, "Preconditions") or ""
    return [re.sub(r"^\d+\.\s*", "", ln.strip())
            for ln in sec.splitlines() if ln.strip()]


def _subgroup_of(fm, concepts):
    """(rel, fm) of the first covering story; falls back to the flow.

    Story-from-covers is tried FIRST so UAT sheets (whose TCs carry a `flow`
    but cover a story AC) group by screen (the member story) rather than
    collapsing every UAT TC under the single flow."""
    for ref in fm.get("covers") or []:
        rel, _frag = resolve_ref(ref)
        sfm = _fm_of(concepts, rel)
        if sfm and sfm.get("type") == "User Story":
            return rel, sfm
    if fm.get("flow"):
        rel = resolve_ref(fm["flow"])[0]
        return rel, _fm_of(concepts, rel)
    return None, None


def _group(tcs, concepts):
    """[(mod_rel, mod_fm, [(sub_rel, sub_fm, [tc, ...]), ...]), ...]
    Modules and subgroups keep first-TC order (tcs arrive sorted)."""
    mods, order = {}, []
    for rel, fm, body in tcs:
        mrel = resolve_ref(fm.get("module") or fm.get("flow") or "unassigned")[0]
        if mrel not in mods:
            mods[mrel] = {}
            order.append(mrel)
        srel, sfm = _subgroup_of(fm, concepts)
        mods[mrel].setdefault(srel, (sfm, []))[1].append((rel, fm, body))
    return [(mrel, _fm_of(concepts, mrel),
             [(srel, sfm, tcl) for srel, (sfm, tcl) in mods[mrel].items()])
            for mrel in order]


def _sheet_name(mod_fm, idx):
    desc = (mod_fm or {}).get("description") or ""
    m = re.search(r"§(\d+(?:\.\d+)*)", desc)
    sec = m.group(1) if m else str(idx + 1)
    title = _plain((mod_fm or {}).get("title") or "Test Cases")
    name = f"C-TC-{sec} ({title})"
    while len(name) > 31:                    # Excel sheet-name hard limit
        words = title.split()
        i = max(range(len(words)), key=lambda j: len(words[j]))
        if len(words[i]) <= 4:
            title = title[:len(title) - (len(name) - 31)].rstrip()
            name = f"C-TC-{sec} ({title})"
            break
        words[i] = words[i][:4]
        title = " ".join(words)
        name = f"C-TC-{sec} ({title})"
    return re.sub(r"[\[\]:*?/\\']", "-", name)


def run_groups(tcs):
    """[(run_name, [tc, ...])] in first-appearance order. A run is one complete
    flow and gets its own worksheet (tc-style R6). Test cases with no `run`
    share one group (name ""), so a set rendered before runs existed keeps one
    sheet."""
    order, groups = [], {}
    for tc in tcs:
        name = tc[1].get("run") or ""
        if name not in groups:
            groups[name] = []
            order.append(name)
        groups[name].append(tc)
    return [(n, groups[n]) for n in order]


def run_sheet_name(run_name, idx):
    """`C-TC-<n> (<run>)`, cut to Excel's 31 characters, with the characters
    Excel forbids in a sheet name replaced by a hyphen. The `<n>` prefix is the
    run's index, so two runs never share a name even when their titles
    truncate to the same text."""
    base = f"C-TC-{idx + 1} ("
    room = 31 - len(base) - 1
    title = _plain(run_name)[:room].rstrip() or "Run"
    return re.sub(r"[\[\]:*?/\\']", "-", f"{base}{title})")


def sheet_common(tcs):
    """Pre-condition lines every test case of one sheet shares: the sheet's
    blue <Pre-condition> block. A chain line is never a shared pre-condition:
    it leads each case's Test Steps (an all-start sheet repeats the same line
    in every case)."""
    pre_lists = [_precond_lines(b) for _r, _f, b in tcs]
    return [ln for ln in (pre_lists[0] if pre_lists else [])
            if not ln.startswith(CHAIN_PREFIXES)
            and all(ln in pl for pl in pre_lists[1:])]


def tc_cells(fm, body, concepts, common, qmap=None):
    """The authored cells of one test-case row, as text that still carries its
    `**bold**` markers. `_fill_tc_sheet` writes exactly these values and the
    operator app's grid reads them through the same call, so the sheet and
    the grid cannot diverge. `chain` and `extra` are the pre-condition lines
    the row lifts into Test Steps and Field / Values."""
    data = body_section(body, "Test Data") or ""
    if data.strip() in BLANK_DATA:
        data = ""
    extra = [ln for ln in _precond_lines(body) if ln not in common]
    chain = [ln for ln in extra if ln.startswith(CHAIN_PREFIXES)]
    extra = [ln for ln in extra if not ln.startswith(CHAIN_PREFIXES)]
    if extra:
        # tc-style R5: TC-specific setup appends as bare lines - no
        # "Pre-condition:" label, no numbering (shared lines live in
        # the sheet's blue <Pre-condition> block).
        lines = "\n".join(extra)
        data = f"{data}\n\n{lines}".strip() if data else lines
    steps = body_section(body, "Steps") or ""
    if chain:
        # "Continue from TC-..." leads the steps, then the flow starts
        steps = "\n".join(chain) + "\n\n" + steps
    return {"id": _display_id(fm),
            "scenario": _scenario_cell(fm, body, concepts),
            "steps": steps, "data": data,
            "expected": body_section(body, "Expected Results") or "",
            "confidence": fm.get("confidence") or "",
            "remarks": _confidence_remarks(fm, qmap),
            "chain": chain, "extra": extra}


_ELEMENT_ITEM_RE = re.compile(rf"(?m)^\d+\. {re.escape(ELEMENT_BLOCK_LEAD)}$")


def split_expected(text):
    """(own items, element block) of an Expected Results text. The renderers
    append the element-verification block as the last numbered item; it is
    derived from the story's coverage map, so the app shows it read-only
    beside the items a human may reword."""
    text = text or ""
    hits = list(_ELEMENT_ITEM_RE.finditer(text))
    if not hits:
        return text, ""
    at = hits[-1].start()
    return text[:at].rstrip("\n"), text[at:]


def plan_sheets(tcs, concepts):
    """[(sheet name, module fm, subs, dashboard title or None)] - the C-TC
    worksheets a selection becomes. One per run when test cases carry `run`;
    otherwise (UAT, older content) one per module. A run sheet keeps the
    module grouping inside it; test cases with no run (mixed selection) form
    one unnamed group that takes the module sheet's name."""
    sheets = []
    if any(fm.get("run") for _r, fm, _b in tcs):
        for ri, (run_name, rtcs) in enumerate(run_groups(tcs)):
            rg = _group(rtcs, concepts)
            subs = [sub for _m, _mf, ss in rg for sub in ss]
            if len(rg) == 1:
                mod_fm = rg[0][1]
            else:
                mod_fm = {"title": " / ".join(
                    (mf or {}).get("title", "?") for _m, mf, _s in rg)}
            name = (run_sheet_name(run_name, ri) if run_name
                    else _sheet_name(rg[0][1], ri))
            sheets.append((name, mod_fm, subs, run_name or None))
    else:
        for i, (_r, mod_fm, subs) in enumerate(_group(tcs, concepts)):
            sheets.append((_sheet_name(mod_fm, i), mod_fm, subs, None))
    return sheets


def _est_height(vals):
    lines = 1
    for col, val in zip("ABCDEFG", vals):
        if not val:
            continue
        w = max(COL_W[col] - 2, 10)
        n = sum(max(1, math.ceil(len(ln) / w)) for ln in _plain(val).split("\n"))
        lines = max(lines, n)
    return min(max(14 * lines, 20), 400)


